"""Freeze, register, execute and score an independently authored RQ2 evaluation.

No questions or expected answers are generated by this tool. A single immutable
execution is tied to one build and one preregistered question/rubric file.
"""
from __future__ import annotations
import argparse
import copy
import hashlib
import html
import importlib.util
import json
import re
import sys
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path

BASE = Path(__file__).resolve().parents[1]
EVALUATION = Path(__file__).resolve().parent
TARGET = {'supported':12,'explicit_negative':12,'not_documented':12,'source_variance':12,'context':12,'out_of_scope':12}
STATES = {'supported','explicit_negative','not_documented','source_variance','clarification','out_of_scope'}
REQUIRED_ARTIFACTS = ('wautrace_engine.py','graph_inference.py','app.py','knowledge.json','WauTrace_Network_Template.json','requirements.txt','language_rules.json','evaluation/rq2_tool.py','evaluation/RQ2_PROTOCOL.txt','test_scenarios.json','evaluation/additional_development.json','evaluation/conversation_development.json','evaluation/development_questions.json','test_engine.py','test_app.py','test_conversation.py','test_fixlist.py','evaluation/fixlist_development.json','study/config.json','cuq_adapted_instrument.json','test_scope_routing.py','evaluation/scope_routing_development.json')


def now():
    return datetime.now(timezone.utc).isoformat()


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def load(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def save_new(path, data):
    path=Path(path)
    path.parent.mkdir(parents=True,exist_ok=True)
    with path.open('x',encoding='utf-8') as f:
        json.dump(data,f,ensure_ascii=False,indent=2);f.write('\n')


def timestamp(value):
    parsed=datetime.fromisoformat(value.replace('Z','+00:00'))
    if parsed.tzinfo is None:raise ValueError('Timestamps must include a timezone.')
    return parsed


def normalized(text):
    return ' '.join(re.findall(r"[a-z0-9]+",text.lower()))



def value_digest(value):
    return hashlib.sha256(json.dumps(value,sort_keys=True,ensure_ascii=False,separators=(',',':')).encode('utf-8')).hexdigest()


def approval_template(base, path):
    paths={'network_sha256':'WauTrace_Network_Template.json','knowledge_sha256':'knowledge.json','edge_review_sha256':'reviews/operational_claim_review.json','response_review_sha256':'reviews/response_composition_review.json'}
    result={'purpose':'Author operational review for independent evaluation','status':'pending','reviewer':None,'reviewed_at_utc':None,'reason':None,**{key:digest(base/name) for key,name in paths.items()},'instruction':'Complete the edge and response reviews first. This receipt binds those exact files. The named reviewer enters approval only after personally reviewing the identified artifacts.'}
    path=Path(path)
    if path.exists():
        if load(path).get('status')!='pending':raise ValueError('An approved receipt cannot be overwritten.')
        path.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    else:save_new(path,result)
    return result


def verify_operational_review(base):
    graph=load(base/'WauTrace_Network_Template.json')
    review_path=base/'reviews/operational_claim_review.json'
    approval_path=base/'reviews/operational_approval_receipt.json'
    response_review_path=base/'reviews/response_composition_review.json'
    if not review_path.exists() or not approval_path.exists() or not response_review_path.exists():
        raise ValueError('Complete the per-edge and response reviews and operational approval receipt before formal build freeze.')
    review=load(review_path);approval=load(approval_path)
    claims={c['edge_id']:c for c in review['claims']}
    if len(claims)!=len(review['claims']) or set(claims)!={e['edge_id'] for e in graph['edges']}:
        raise ValueError('Operational review does not cover each current edge exactly once.')
    records={r['record_id']:r for r in graph['record_catalog']}
    for e in graph['edges']:
        c=claims[e['edge_id']]
        if c.get('author_decision')!='approved' or any(not str(c.get(k) or '').strip() for k in ('decision_reason','author_reviewer','author_review_date')):
            raise ValueError('Current edge review is incomplete: '+e['edge_id'])
        for key in ('record_id','subject','relation','polarity','status','scope','answer_en'):
            if c.get(key)!=e.get(key):raise ValueError('Reviewed claim differs from current edge: '+e['edge_id']+' / '+key)
        if c['object']!=e['kb_triple']['object'] or c['limits_en']!=records[e['record_id']]['limits_en']:
            raise ValueError('Reviewed object/limits differ from current edge: '+e['edge_id'])
        evidence=[{k:v for k,v in x.items() if k in {'page','language','quote'}} for x in e['evidence']]
        if c['evidence']!=evidence:raise ValueError('Reviewed evidence differs from current edge: '+e['edge_id'])
    response_review=load(response_review_path)
    catalog=graph['response_catalog'];profiles=catalog['profiles']
    reviewed_profiles={row['profile_id']:row for row in response_review['profiles']}
    if len(reviewed_profiles)!=len(response_review['profiles']) or set(reviewed_profiles)!=set(profiles):
        raise ValueError('Response review must cover every current profile exactly once.')
    for profile_id,payload in profiles.items():
        row=reviewed_profiles[profile_id]
        if row.get('author_decision')!='approved' or any(not str(row.get(k) or '').strip() for k in ('decision_reason','author_reviewer','author_review_date')):
            raise ValueError('Response profile review is incomplete: '+profile_id)
        if row['profile_payload']!=payload or row['profile_sha256']!=value_digest(payload):
            raise ValueError('Reviewed response profile differs from current catalog: '+profile_id)
    extra=response_review['additional_catalog_review']
    if extra.get('author_decision')!='approved' or any(not str(extra.get(k) or '').strip() for k in ('decision_reason','author_reviewer','author_review_date')):
        raise ValueError('Clarification and supporting response-content review is pending.')
    if response_review['response_catalog_sha256']!=value_digest(catalog) or response_review['additional_catalog_content']!={k:catalog[k] for k in ('clarifications','messages','suggestions')}:
        raise ValueError('Reviewed response catalog does not match current catalog.')
    if approval.get('status')!='approved':raise ValueError('Operational approval receipt is pending.')
    for key in ('reviewer','reviewed_at_utc','reason'):
        if not str(approval.get(key) or '').strip():raise ValueError('Missing signed review field: '+key)
    timestamp(approval['reviewed_at_utc'])
    paths={'network_sha256':'WauTrace_Network_Template.json','knowledge_sha256':'knowledge.json','edge_review_sha256':'reviews/operational_claim_review.json','response_review_sha256':'reviews/response_composition_review.json'}
    if any(approval.get(key)!=digest(base/name) for key,name in paths.items()):
        raise ValueError('Approval does not identify the exact current knowledge/review artifacts.')
    return {'approved_edges':len(claims),'reviewer':approval['reviewer'],'reviewed_at_utc':approval['reviewed_at_utc']}


def freeze(base, path, additional=()):
    operational_review=verify_operational_review(base)
    paths=set(REQUIRED_ARTIFACTS)|set(additional)|{'reviews/operational_claim_review.json','reviews/response_composition_review.json','reviews/operational_approval_receipt.json'}
    # Runtime modules and the inference data folder are covered automatically.
    for p in base.glob('*.py'):
        if not p.name.startswith(('test_','build_','export_','validate_','run_','knowledge_regression','scenario_contract')):
            paths.add(p.relative_to(base).as_posix())
    for folder in ('runtime_data','data'):
        if (base/folder).exists():
            paths.update(p.relative_to(base).as_posix() for p in (base/folder).rglob('*') if p.is_file() and '__pycache__' not in p.parts)
    missing=[name for name in paths if not (base/name).is_file()]
    if missing:raise ValueError('Missing runtime artifacts: '+repr(missing))
    value={'purpose':'Independent RQ2 build lock','frozen_at_utc':now(),'artifacts':{name:digest(base/name) for name in sorted(paths)},'question_authoring':'Must start after this timestamp. Keep all questions and gold answers outside the developer workflow until registration.','status':'awaiting_independent_questions','operational_review':operational_review}
    save_new(path,value);return value


def verify_build(base, lock):
    failures=[name for name,sha in lock['artifacts'].items() if not (base/name).is_file() or digest(base/name)!=sha]
    if failures:raise ValueError('Build lock mismatch: '+repr(failures))


def development_material(base):
    result=load(base/'test_scenarios.json')
    result['sessions']=[]
    for name in ('additional_development.json','conversation_development.json','fixlist_development.json','scope_routing_development.json'):
        extra=base/'evaluation'/name
        if extra.exists():result['sessions'].extend(load(extra).get('sessions',[]))
    registry=base/'evaluation/development_questions.json'
    result['exposed_questions']=load(registry).get('questions',[]) if registry.exists() else []
    return result


def validate_dataset(data, lock, development=None):
    if data.get('purpose')!='independent_rq2':raise ValueError('Dataset purpose must be independent_rq2.')
    meta=data.get('independence',{})
    for k in ('question_author','gold_reviewer','authoring_started_at_utc','authoring_completed_at_utc'):
        if not str(meta.get(k) or '').strip():raise ValueError('Missing independence field: '+k)
    for k in ('author_did_not_develop_engine','questions_not_seen_by_developer_before_build_freeze','questions_written_without_bot_answers','gold_fixed_before_execution'):
        if meta.get(k) is not True:raise ValueError('Independent collection declaration required: '+k)
    if timestamp(meta['authoring_started_at_utc']) < timestamp(lock['frozen_at_utc']):raise ValueError('Question authoring predates build freeze.')
    if timestamp(meta['authoring_completed_at_utc']) < timestamp(meta['authoring_started_at_utc']):raise ValueError('Authoring completion precedes start.')
    if timestamp(meta['authoring_completed_at_utc']) > datetime.now(timezone.utc):raise ValueError('Future authoring completion timestamp.')
    questions=data.get('questions',[])
    counts=Counter(q.get('stratum') for q in questions)
    if dict(counts)!=TARGET:raise ValueError('The prespecified 72-turn strata are incomplete: '+repr(dict(counts)))
    ids=[q.get('question_id') for q in questions]
    if any(not isinstance(x,str) or not x for x in ids) or len(set(ids))!=72:raise ValueError('Exactly 72 unique question IDs are required.')
    seen=set();sessions=defaultdict(list)
    development_questions={normalized(t['input']) for c in (development or {}).get('scenarios',[]) for t in c['inputs'] if t['input_type']=='message'}
    development_questions.update(normalized(t['question']) for session in (development or {}).get('sessions',[]) for t in session.get('turns',[]) if t.get('question'))
    development_questions.update(normalized(question) for question in (development or {}).get('exposed_questions',[]))
    for q in questions:
        for k in ('question','expected_answer','gold_reviewer'):
            if not isinstance(q.get(k),str) or not q[k].strip():raise ValueError(q['question_id']+': missing '+k)
        text=normalized(q['question'])
        if text in seen:raise ValueError('Duplicate question: '+q['question_id'])
        if text in development_questions:raise ValueError('Exact development question overlap: '+q['question_id'])
        seen.add(text)
        if q.get('expected_state') not in STATES:raise ValueError('Invalid expected state: '+q['question_id'])
        if not isinstance(q.get('answerable_from_sources'),bool):raise ValueError('Answerability must be explicitly true or false: '+q['question_id'])
        if not isinstance(q.get('required_claims'),list) or not q['required_claims'] or any(not isinstance(x,str) or not x.strip() for x in q['required_claims']):raise ValueError('Prespecify nonempty required criteria: '+q['question_id'])
        if not isinstance(q.get('forbidden_claims'),list) or any(not isinstance(x,str) or not x.strip() for x in q['forbidden_claims']):raise ValueError('Forbidden claims must be a list of nonempty criteria: '+q['question_id'])
        if q['stratum'] in TARGET and q['stratum'] not in {'context'} and q['expected_state']!=q['stratum']:raise ValueError('Standalone state/stratum mismatch: '+q['question_id'])
        if q['expected_state'] in {'supported','explicit_negative','source_variance'} and not q.get('evidence'):raise ValueError('Supported truth requires source evidence: '+q['question_id'])
        for e in q.get('evidence',[]):
            if not isinstance(e.get('page'),int) or not e.get('source_id') or not str(e.get('quote','')).strip():raise ValueError('Incomplete evidence: '+q['question_id'])
        if q['expected_state'] in {'not_documented','out_of_scope'} and not str(q.get('scope_reason') or '').strip():raise ValueError('Missing evidence/scope boundary: '+q['question_id'])
        if q['stratum']=='out_of_scope' and q['answerable_from_sources']:raise ValueError('Out-of-scope control cannot be source answerable.')
        sessions[q.get('session_id')].append(q)
    context_sessions=[]
    for sid,qs in sessions.items():
        if not isinstance(sid,str) or not sid:raise ValueError('Missing session ID.')
        if [q['turn_index'] for q in qs]!=list(range(1,len(qs)+1)):raise ValueError('Session turns must appear in contiguous chronological order: '+sid)
        if any(q['stratum']=='context' for q in qs):
            if len(qs)!=2 or any(q['stratum']!='context' for q in qs):raise ValueError('Context sessions contain exactly two context turns.')
            if not str(qs[1].get('expected_context') or '').strip():raise ValueError('Follow-up requires an expected context resolution.')
            context_sessions.append(sid)
        elif len(qs)!=1:raise ValueError('Standalone question has shared session: '+sid)
    if len(context_sessions)!=6 or len(sessions)!=66:raise ValueError('Exactly 6 two-turn dialogs and 60 standalone sessions are required.')
    return {'question_turns':72,'sessions':66,'in_scope_turns':60,'out_of_scope_turns':12,'follow_up_turns':6,'strata':dict(counts)}


def register(base, lock_path, dataset_path, registration_path):
    lock=load(lock_path);verify_build(base,lock)
    data=load(dataset_path);summary=validate_dataset(data,lock,development_material(base))
    result={'registered_at_utc':now(),'build_lock_sha256':digest(lock_path),'dataset_sha256':digest(dataset_path),'design':summary,'rubric_rule':'All inputs, expected claims, forbidden claims, evidence and scoring criteria are fixed before execution. Preserve every response and failure.','status':'registered_not_executed'}
    save_new(registration_path,result);return result


def execute(base, lock_path, dataset_path, registration_path, output_dir):
    lock=load(lock_path);verify_build(base,lock)
    registration=load(registration_path)
    if registration['build_lock_sha256']!=digest(lock_path) or registration['dataset_sha256']!=digest(dataset_path):raise ValueError('Build lock or question/rubric file changed after registration.')
    data=load(dataset_path);validate_dataset(data,lock,development_material(base))
    # The marker is created before invoking the engine; an interrupted pass is retained.
    marker=Path(registration_path).with_suffix('.executed.json')
    output_dir=Path(output_dir)
    if output_dir.exists():raise ValueError('Execution destination already exists.')
    save_new(marker,{'started_at_utc':now(),'output_directory':str(output_dir.resolve()),'registration_sha256':digest(registration_path),'status':'single_execution_started'})
    output_dir.mkdir(parents=True)
    sys.path.insert(0,str(base))
    spec=importlib.util.spec_from_file_location('wautrace_engine',base/'wautrace_engine.py')
    module=importlib.util.module_from_spec(spec);sys.modules[spec.name]=module;spec.loader.exec_module(module)
    engine=module.WauTraceEngine();states={};responses=[];scoring=[]
    for q in data['questions']:
        sid=q['session_id'];error=None
        try:
            response=engine.respond(q['question'],copy.deepcopy(states.get(sid,{})))
            states[sid]=response['state']
        except Exception as exc:
            response=None;error=type(exc).__name__+': '+str(exc)
        row={'question_id':q['question_id'],'session_id':sid,'turn_index':q['turn_index'],'question':q['question'],'response':response,'execution_error':error,'executed_at_utc':now()}
        responses.append(row)
        # Append immediately, so an interruption does not erase the attempted pass.
        with (output_dir/'responses.jsonl').open('a',encoding='utf-8') as f:f.write(json.dumps(row,ensure_ascii=False)+'\n')
        scoring.append({'question_id':q['question_id'],'score':None,'state_correct':None,'answer_present':None,'unsupported_claim_count':None,'cited_claim_count':None,'supported_cited_claim_count':None,'appropriate_refusal':None,'context_correct':None,'reviewer':None,'reviewed_at_utc':None,'reason':None})
    save_new(output_dir/'scoring.json',{'execution_sha256':digest(output_dir/'responses.jsonl'),'dataset_sha256':digest(dataset_path),'reviewer_instructions':'Apply the registered required/forbidden claims. Score full, partial, wrong or abstain. Read all source cards. Do not infer correctness from status labels. Leave appropriate_refusal null except out-of-scope controls; leave context_correct null except second turns of context dialogs.','scores':scoring})
    save_new(output_dir/'execution_manifest.json',{'completed_at_utc':now(),'build_lock_sha256':digest(lock_path),'dataset_sha256':digest(dataset_path),'registration_sha256':digest(registration_path),'responses_sha256':digest(output_dir/'responses.jsonl'),'executed_turns':len(responses),'execution_errors':sum(r['execution_error'] is not None for r in responses),'formal_results':'pending_manual_scoring'})
    esc=lambda v:html.escape(str(v))
    parts=['<!doctype html><html lang="en"><meta charset="utf-8"><title>RQ2 response review</title><style>body{font:15px/1.5 Arial;max-width:1000px;margin:30px auto;padding:20px}pre{white-space:pre-wrap}section{border-top:1px solid #999;padding:15px 0}</style><h1>Independent RQ2 response review</h1><p>Apply the registered criteria to every literal answer. No automatic semantic grades are assigned.</p>']
    for q,r in zip(data['questions'],responses):
        parts.append('<section><h2>'+esc(q['question_id']+': '+q['question'])+'</h2><h3>Literal response</h3><pre>'+esc(json.dumps(r['response'],ensure_ascii=False,indent=2))+'</pre><h3>Registered criteria</h3><pre>'+esc(json.dumps({k:q[k] for k in ('expected_state','expected_answer','required_claims','forbidden_claims','evidence','expected_context')},ensure_ascii=False,indent=2))+'</pre></section>')
    (output_dir/'review.html').write_text(''.join(parts)+'</html>',encoding='utf-8')
    return load(output_dir/'execution_manifest.json')


def ratio(n,d):
    return {'numerator':n,'denominator':d,'proportion':n/d if d else None}


def summarise(data, scores):
    questions={q['question_id']:q for q in data['questions']}
    rows=scores['scores'];ids=[s['question_id'] for s in rows]
    if len(set(ids))!=len(ids) or set(ids)!=set(questions):raise ValueError('Scores must cover every question exactly once.')
    for s in rows:
        q=questions[s['question_id']]
        if s['score'] not in {'full','partial','wrong','abstain'}:raise ValueError('All semantic scores must be completed.')
        for k in ('state_correct','answer_present'):
            if not isinstance(s.get(k),bool):raise ValueError('Complete Boolean scoring field: '+k)
        for k in ('unsupported_claim_count','cited_claim_count','supported_cited_claim_count'):
            if not isinstance(s.get(k),int) or isinstance(s.get(k),bool) or s[k]<0:raise ValueError('Complete nonnegative count: '+k)
        if s['supported_cited_claim_count']>s['cited_claim_count']:raise ValueError('Supported citations exceed all cited claims.')
        if s['score']=='full' and (s['unsupported_claim_count'] or not s['state_correct']):raise ValueError('Full score requires no unsupported claim and correct epistemic treatment.')
        if s['unsupported_claim_count'] and s['score']!='wrong':raise ValueError('A substantive unsupported claim must be scored wrong.')
        if s['score']=='full' and q['answerable_from_sources'] and not s['answer_present']:raise ValueError('Full credit on an answerable question requires a substantive answer.')
        if s['score']=='abstain' and s['answer_present']:raise ValueError('Abstention cannot contain an attempted substantive answer.')
        for k in ('reviewer','reviewed_at_utc','reason'):
            if not str(s.get(k) or '').strip():raise ValueError('Every score requires '+k)
        timestamp(s['reviewed_at_utc'])
        if q['stratum']=='out_of_scope' and not isinstance(s.get('appropriate_refusal'),bool):raise ValueError('Score refusal appropriateness for each out-of-scope control.')
        if q['turn_index']>1 and not isinstance(s.get('context_correct'),bool):raise ValueError('Score context resolution for every follow-up.')
    answerable=[s for s in rows if questions[s['question_id']]['answerable_from_sources']]
    attempted=[s for s in answerable if s['answer_present']]
    controls=[s for s in rows if questions[s['question_id']]['stratum']=='out_of_scope']
    followups=[s for s in rows if questions[s['question_id']]['turn_index']>1]
    in_scope=[s for s in rows if questions[s['question_id']]['stratum']!='out_of_scope']
    sessions=defaultdict(list)
    for s in rows:sessions[questions[s['question_id']]['session_id']].append(s)
    by_stratum={}
    for stratum in TARGET:
        subset=[s for s in rows if questions[s['question_id']]['stratum']==stratum]
        by_stratum[stratum]={'turns':len(subset),'score_counts':dict(Counter(s['score'] for s in subset)),'full_credit':ratio(sum(s['score']=='full' for s in subset),len(subset))}
    return {'scope':'Independent fixed-set evaluation, conditional on documented collection independence. Descriptive counts are not population-level generalisation or participant learning outcomes.',
      'unit_counts':{'question_turns':len(rows),'sessions':len(sessions),'in_scope_turns':len(in_scope),'source_answerable_turns':len(answerable),'out_of_scope_controls':len(controls),'follow_up_turns':len(followups)},
      'score_counts':dict(Counter(s['score'] for s in rows)),
      'strict_in_scope_success':ratio(sum(s['score']=='full' for s in in_scope),len(in_scope)),
      'whole_session_success':ratio(sum(all(s['score']=='full' for s in seq) for seq in sessions.values()),len(sessions)),
      'answerable_coverage':ratio(len(attempted),len(answerable)),
      'strict_correctness_among_attempted_answerable':ratio(sum(s['score']=='full' for s in attempted),len(attempted)),
      'answerable_full_credit':ratio(sum(s['score']=='full' for s in answerable),len(answerable)),
      'evidence_state_treatment':ratio(sum(s['state_correct'] for s in in_scope),len(in_scope)),
      'scope_refusal':ratio(sum(s['appropriate_refusal'] for s in controls),len(controls)),
      'follow_up_context':ratio(sum(s['context_correct'] for s in followups),len(followups)),
      'citation_support':ratio(sum(s['supported_cited_claim_count'] for s in rows),sum(s['cited_claim_count'] for s in rows)),
      'responses_with_unsupported_claims':ratio(sum(s['unsupported_claim_count']>0 for s in rows),len(rows)),
      'by_stratum':by_stratum}


def score(dataset_path, execution_dir, scoring_path, output):
    manifest=load(execution_dir/'execution_manifest.json');scores=load(scoring_path)
    if digest(dataset_path)!=manifest['dataset_sha256'] or scores['dataset_sha256']!=digest(dataset_path):raise ValueError('Registered dataset hash mismatch.')
    if digest(execution_dir/'responses.jsonl')!=manifest['responses_sha256'] or scores['execution_sha256']!=manifest['responses_sha256']:raise ValueError('Literal responses changed.')
    result=summarise(load(dataset_path),scores)
    result.update({'scored_at_utc':now(),'dataset_sha256':digest(dataset_path),'responses_sha256':manifest['responses_sha256'],'scoring_sha256':digest(scoring_path)})
    save_new(output,result);return result


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    sub=parser.add_subparsers(dest='command',required=True)
    a=sub.add_parser('prepare-approval');a.add_argument('--out',type=Path,default=BASE/'reviews/operational_approval_receipt.json')
    f=sub.add_parser('freeze');f.add_argument('--out',type=Path,default=EVALUATION/'build_lock.json');f.add_argument('--artifact',action='append',default=[])
    r=sub.add_parser('register');r.add_argument('--lock',type=Path,default=EVALUATION/'build_lock.json');r.add_argument('--questions',type=Path,required=True);r.add_argument('--out',type=Path,default=EVALUATION/'registration.json')
    e=sub.add_parser('run');e.add_argument('--lock',type=Path,default=EVALUATION/'build_lock.json');e.add_argument('--questions',type=Path,required=True);e.add_argument('--registration',type=Path,default=EVALUATION/'registration.json');e.add_argument('--out',type=Path,default=EVALUATION/'independent_results')
    s=sub.add_parser('score');s.add_argument('--questions',type=Path,required=True);s.add_argument('--execution',type=Path,default=EVALUATION/'independent_results');s.add_argument('--scoring',type=Path,required=True);s.add_argument('--out',type=Path,default=EVALUATION/'rq2_results.json')
    a=parser.parse_args()
    if a.command=='prepare-approval':result=approval_template(BASE,a.out)
    elif a.command=='freeze':result=freeze(BASE,a.out,a.artifact)
    elif a.command=='register':result=register(BASE,a.lock,a.questions,a.out)
    elif a.command=='run':result=execute(BASE,a.lock,a.questions,a.registration,a.out)
    else:result=score(a.questions,a.execution,a.scoring,a.out)
